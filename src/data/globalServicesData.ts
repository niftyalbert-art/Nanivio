// Master Function: Resolve places based on city and country
export const getPlacesForLocation = (city: string, country: string): NearbyLivePlace[] => {
  const normCity = (city || '').trim().toLowerCase();
  const normCountry = (country || '').trim().toLowerCase();

  if (normCity.includes('kumasi') || (normCountry === 'ghana' && normCity === 'kumasi')) {
    return KUMASI_PLACES;
  }

  if (normCity.includes('accra') || (normCountry === 'ghana' && normCity === 'accra')) {
    return NEARBY_PLACES;
  }

  if (normCity.includes('lagos') || (normCountry === 'nigeria' && normCity === 'lagos')) {
    return LAGOS_PLACES;
  }

  if (normCity.includes('london') || (normCountry.includes('united kingdom') && normCity === 'london')) {
    return LONDON_PLACES;
  }

  // Live production: do not generate fake mocks; leave empty until a real user/business registers
  return [];
};
