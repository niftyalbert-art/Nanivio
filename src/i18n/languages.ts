// Dynamic Runtime Registry
let runtimeRegistry: LanguageRegistryItem[] = [...INITIAL_LANGUAGE_REGISTRY];

/**
 * Register new languages at runtime without modifying source code
 */
export function registerLanguage(lang: LanguageRegistryItem): void {
  const existingIdx = runtimeRegistry.findIndex((l) => l.code === lang.code);
  if (existingIdx >= 0) {
    runtimeRegistry[existingIdx] = lang;
  } else {
    runtimeRegistry.push(lang);
  }
}

export function getAllLanguages(): LanguageRegistryItem[] {
  return runtimeRegistry;
}

export function getLanguageByCode(code: string): LanguageRegistryItem | undefined {
  return runtimeRegistry.find((l) => l.code.toLowerCase() === code.toLowerCase());
}

export function getUILanguages(): LanguageRegistryItem[] {
  return runtimeRegistry.filter((l) => l.ui);
}

export function getTranslationLanguages(): LanguageRegistryItem[] {
  return runtimeRegistry.filter((l) => l.translation);
}

export function getVoiceLanguages(): LanguageRegistryItem[] {
  return runtimeRegistry.filter((l) => l.voiceTranslation || l.speechRecognition);
}
